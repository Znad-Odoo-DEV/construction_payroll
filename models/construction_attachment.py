# -*- coding: utf-8 -*-
import logging
from collections import defaultdict
from datetime import date

from dateutil.relativedelta import relativedelta

from odoo import api, fields, models
from odoo.exceptions import UserError
from odoo.tools.misc import formatLang

from .utils import MONTH_ABBR

_logger = logging.getLogger(__name__)

MONTH_NUMBER = {abbr: number for number, abbr in MONTH_ABBR.items()}

# The system parameter naming the first payroll month (YYYY-MM) whose payslips
# take their lines from the Salary Adjustments. Optional: when it is set, an
# older payslip attached again is not paid an allowance it never had.
ADJUSTMENTS_FROM_PARAM = 'construction_payroll.salary_adjustments_from'

# Under this, what a limited adjustment has left is rounding, not money owed:
# an advance of 1,000 in three installments of 333.33 leaves 0.01, which no
# payslip should carry as a line of its own and which must not keep the
# adjustment running for ever.
ROUNDING_LEFTOVER = 1.0

class ConstructionAttachment(models.Model):
    _name = 'construction.attachment'
    _description = "Salary Attachment"
    _inherit = ['mail.thread']
    _order = 'year desc, month desc, id desc'

    name = fields.Char(string="Description", required=True)
    employee_id = fields.Many2one(
        'hr.employee', string="Employee", required=True, index=True, tracking=True,
    )
    company_id = fields.Many2one(related='employee_id.company_id', store=True, index=True)
    currency_id = fields.Many2one(related='employee_id.currency_id', store=True)
    type_id = fields.Many2one('construction.attachment.type', string="Type", required=True)
    factor = fields.Integer(related='type_id.factor', store=True)
    # Period the attachment belongs to (matched against the payslip period).
    # Prefilled from today's date on a new record, but editable.
    month = fields.Selection(
        [
            ('JAN', 'JAN'), ('FEB', 'FEB'), ('MAR', 'MAR'), ('APR', 'APR'),
            ('MAY', 'MAY'), ('JUN', 'JUN'), ('JUL', 'JUL'), ('AUG', 'AUG'),
            ('SEP', 'SEP'), ('OCT', 'OCT'), ('NOV', 'NOV'), ('DEC', 'DEC'),
        ],
        string="Month", required=True, default=lambda self: self._default_month(),
    )
    year = fields.Char(
        string="Year", required=True, default=lambda self: self._default_year())
    # Day the attachment refers to, when the month is not specific enough: an
    # employee can have several sick leaves inside one month, and each must
    # produce its own reimbursement.
    day = fields.Date(string="Day")
    value = fields.Monetary(string="Value")
    signed_value = fields.Monetary(
        string="Signed Value", compute='_compute_signed_value', store=True,
        help="Value with the type's sign applied (+ addition / - deduction).",
    )
    payslip_id = fields.Many2one('construction.payslip', string="Payslip", index=True)
    # Optional source documents this attachment was generated from.
    fine_id = fields.Many2one('construction.fine', string="Fine", index=True, ondelete='cascade')
    advance_id = fields.Many2one('construction.advance', string="Advance", index=True, ondelete='cascade')
    installment_id = fields.Many2one(
        'construction.advance.installment', string="Installment", index=True, ondelete='set null',
        help="The advance installment this deduction settles.")
    # The Salary Adjustment on the employee this row is one month of. The
    # payslip that pays the row records the payment on the adjustment, which
    # closes itself once its total is paid.
    salary_adjustment_id = fields.Many2one(
        'hr.salary.attachment', string="Salary Adjustment", index=True, copy=False,
        ondelete='set null', readonly=True,
        help="The employee's Salary Adjustment this line is the month of.")
    # Staff last-month absence deduction: kept in step with the staff line's
    # last_month_absence (fix the day count, the value follows - no delete/recreate).
    staff_line_id = fields.Many2one(
        'construction.staff.attendance.line', string="Staff Line", index=True, ondelete='cascade')
    leave_expense_id = fields.Many2one('construction.leave.expense', string="Leave Expense", index=True, ondelete='cascade')
    state = fields.Selection(
        [('new', 'New'), ('attached', 'Attached'), ('paid', 'Paid')],
        string="Status", default='new', tracking=True, index=True,
    )
    # Written by the payroll engine on everything it creates for a period.
    # It is what lets a re-generation replace its own previous output: the
    # description carries the day count and the dates, so a recalculation
    # renames the attachment, and identity by wording is no identity at all.
    # Nothing a person typed carries this flag, and nothing paid is touched.
    auto_generated = fields.Boolean(string="Generated by Payroll", copy=False)

    @api.model
    def _default_month(self):
        return MONTH_ABBR[fields.Date.context_today(self).month]

    @api.model
    def _default_year(self):
        return str(fields.Date.context_today(self).year)

    @api.depends('value', 'factor')
    def _compute_signed_value(self):
        for rec in self:
            rec.signed_value = rec.value * (rec.factor or 0)

    @api.model_create_multi
    def create(self, vals_list):
        records = super().create(vals_list)
        records._construction_settle_adjustments({}, records._construction_adjustment_paid())
        return records

    # What a paid line says is what a salary paid: it changes only by resetting
    # its payslip, which takes the payment back first.
    _LOCKED_ONCE_PAID = ('value', 'type_id', 'month', 'year', 'employee_id', 'payslip_id', 'state')

    def _construction_engine(self):
        """True for payroll's own writes (and for scripts run as the system)."""
        return self.env.su or self.env.context.get('construction_payroll_engine')

    def _construction_changes(self, field, value):
        """The records whose ``field`` would really change to ``value``."""
        def differs(rec):
            current = rec[field]
            if self._fields[field].type == 'many2one':
                return current.id != (value or False)
            if self._fields[field].type in ('monetary', 'float'):
                return abs((current or 0.0) - (value or 0.0)) > 0.005
            return (current or False) != (value or False)
        return self.filtered(differs)

    def _construction_check_write(self, vals):
        if self._construction_engine():
            return
        paid = self.filtered(lambda a: a.state == 'paid')
        for field in self._LOCKED_ONCE_PAID:
            if field in vals and paid._construction_changes(field, vals[field]):
                raise UserError(self.env._(
                    "%s is on a paid salary and cannot be changed. Reset its "
                    "payslip first: that takes the payment back, and paying it "
                    "again records what it then says.", paid[:1].display_name))
        for field in ('month', 'year'):
            if field in vals:
                moved = self.filtered('salary_adjustment_id')._construction_changes(field, vals[field])
                if moved:
                    raise UserError(self.env._(
                        "%s is the month of a Salary Adjustment; its month cannot be "
                        "changed. To skip or ease this month, change its value (0 "
                        "skips it): what is not taken now stays owed.",
                        moved[:1].display_name))

    def write(self, vals):
        self._construction_check_write(vals)
        settles = bool({'state', 'value', 'salary_adjustment_id'} & set(vals))
        paid_before = self._construction_adjustment_paid() if settles else {}
        res = super().write(vals)
        if settles:
            self._construction_settle_adjustments(paid_before, self._construction_adjustment_paid())
        # A month of a Salary Adjustment whose amount a person changed (0 to
        # skip the month, less to go easy on it) is that person's decision:
        # it stops being the engine's row, so generating the period again
        # keeps it instead of putting the full installment back.
        if 'value' in vals:
            edited = self.filtered(lambda a: a.salary_adjustment_id and a.auto_generated)
            if edited:
                super(ConstructionAttachment, edited).write({'auto_generated': False})
        # Detaching from a payslip (its link cleared, e.g. the payslip was
        # deleted and rebuilt) frees the attachment: reset it to New so the next
        # payslip for the same period re-collects it. Paid ones are never demoted.
        if 'payslip_id' in vals and not vals.get('payslip_id'):
            self.filtered(lambda a: a.state == 'attached').write({'state': 'new'})
        # The installment follows its deduction: paid when the payslip that
        # carries it is paid, open again if that is undone.
        if 'state' in vals or 'payslip_id' in vals:
            with_installment = self.filtered('installment_id')
            for att in with_installment:
                paid = att.state == 'paid'
                if att.installment_id.paid != paid:
                    att.installment_id.paid = paid
            with_installment.mapped('advance_id')._refresh_state()
        return res

    def unlink(self):
        if not self._construction_engine():
            paid = self.filtered(lambda a: a.state == 'paid')
            if paid:
                raise UserError(self.env._(
                    "%s is on a paid salary and cannot be deleted. Reset its "
                    "payslip first.", paid[:1].display_name))
            monthly = self.filtered('salary_adjustment_id')
            if monthly:
                raise UserError(self.env._(
                    "%s is the month of a Salary Adjustment: deleted, it would come "
                    "back the next time the payslip collects its lines. Set its "
                    "value to 0 to skip this month instead; what is not taken stays "
                    "owed.", monthly[:1].display_name))
        installments = self.mapped('installment_id')
        if installments.filtered('paid'):
            raise UserError(self.env._(
                "A deduction already taken from a paid salary cannot be deleted."))
        advances = installments.mapped('advance_id')
        paid_before = self._construction_adjustment_paid()
        res = super().unlink()
        advances._refresh_state()
        self._construction_settle_adjustments(paid_before, {})
        return res

    # ------------------------------------------------------------------
    # Salary Adjustments (hr.salary.attachment) on payroll.
    #
    # An adjustment is kept on the employee: an advance being paid back, a
    # monthly phone allowance. Every month the payslip collects its
    # attachments, each running adjustment puts that month's row here, and
    # the row travels like any other: it shows on the payslip, counts in the
    # net, prints, posts. When the payslip is paid, the adjustment records
    # the payment and closes once its total is reached.
    #
    # Payroll's model is read and written with sudo(): the payroll officer
    # generating a payslip need not hold rights on it, and only the running
    # adjustments of the payslip's own employee are touched.
    # ------------------------------------------------------------------
    def _construction_adjustment_paid(self):
        """{adjustment id: amount} these rows have paid against their
        Salary Adjustments: the value of every paid row linked to one."""
        paid = defaultdict(float)
        for att in self:
            if att.salary_adjustment_id and att.state == 'paid':
                paid[att.salary_adjustment_id.id] += abs(att.value)
        return paid

    @api.model
    def _construction_settle_adjustments(self, before, after):
        """Move each adjustment's paid amount by what its rows' payments
        changed: a row paid adds its value, a payment undone takes it back."""
        if not (before or after) or self.env.context.get('construction_skip_adjustment_settlement'):
            return
        Adjustment = self.env['hr.salary.attachment'].sudo()
        for adjustment in Adjustment.browse(sorted(set(before) | set(after))).exists():
            currency = adjustment.currency_id
            delta = after.get(adjustment.id, 0.0) - before.get(adjustment.id, 0.0)
            if currency.is_zero(delta) or len(adjustment.employee_ids) > 1:
                continue
            paid = adjustment.paid_amount + delta
            if adjustment.has_total_amount:
                paid = min(paid, adjustment.total_amount)
            adjustment.paid_amount = max(paid, 0.0)
            amount = formatLang(self.env, abs(delta), currency_obj=currency)
            adjustment.message_post(body=(
                self.env._("Paid on the payslip: %s.", amount) if delta > 0
                else self.env._("Payment of %s taken back: the payslip line is no longer paid.", amount)))
            if not adjustment.has_total_amount:
                continue
            settled = adjustment.remaining_amount < ROUNDING_LEFTOVER
            if settled and adjustment.state == 'open':
                adjustment.action_close()
            elif not settled and adjustment.state == 'close' and delta < 0:
                adjustment.write({'state': 'open', 'date_end': False})
        self.env['construction.advance'].sudo().search([
            ('salary_adjustment_id', 'in', sorted(set(before) | set(after))),
        ])._refresh_state()

    @api.model
    def _construction_adjustments_from(self):
        """The first payroll month the Salary Adjustments reach, or None
        when the parameter is unset (every month then)."""
        value = self.env['ir.config_parameter'].sudo().get_param(ADJUSTMENTS_FROM_PARAM)
        try:
            year, month = (int(part) for part in (value or '').split('-')[:2])
            return date(year, month, 1)
        except ValueError:
            return None

    @api.model
    def _construction_lines_from_adjustments(self, employee, month, year):
        """Put this month of the employee's running Salary Adjustments on
        payroll, one row per adjustment, and return the rows.

        Idempotent: a second call finds each row and makes nothing. A limited
        adjustment never asks for more than is left of its total, counting
        what earlier months already put on payslips that are not paid yet.
        A row made for this month before the adjustment existed (an advance's
        deduction scheduled ahead, or one typed by hand) becomes this
        month's row instead of being doubled.
        """
        month_no = MONTH_NUMBER.get(month)
        year = str(year or '')
        if not employee or not month_no or not year.isdigit():
            return self.browse()
        first = date(int(year), month_no, 1)
        last = first + relativedelta(months=1, days=-1)
        start = self._construction_adjustments_from()
        if start and first < start:
            return self.browse()
        adjustments = self.env['hr.salary.attachment'].sudo().search([
            ('employee_ids', 'in', employee.ids),
            ('state', '=', 'open'),
            ('date_start', '<=', last),
            '|', ('date_end', '=', False), ('date_end', '>=', first),
        ], order='date_start, id')
        if not adjustments:
            return self.browse()

        Row = self.sudo()
        Type = self.env['construction.attachment.type'].sudo()
        Advance = self.env['construction.advance'].sudo()
        linked = Row.search([
            ('salary_adjustment_id', 'in', adjustments.ids),
            ('employee_id', '=', employee.id),
        ])
        made = Row.browse()
        for adjustment in adjustments:
            if len(adjustment.employee_ids) > 1 and adjustment.has_total_amount:
                # Its paid amount is shared; whose payment is whose cannot be told.
                _logger.warning(
                    "construction_payroll: Salary Adjustment %s has a total and several "
                    "employees; it is not put on construction.payslip", adjustment.id)
                continue
            rows = linked.filtered(lambda r: r.salary_adjustment_id == adjustment)
            if rows.filtered(lambda r: r.month == month and r.year == year):
                continue
            if adjustment.duration_type == 'one' and rows:
                continue
            amount = adjustment.monthly_amount
            if adjustment.has_total_amount:
                pending = sum(abs(r.value) for r in rows if r.state != 'paid')
                amount = min(amount, adjustment.total_amount - adjustment.paid_amount - pending)
            amount = adjustment.currency_id.round(amount)
            if amount <= 0 or (adjustment.has_total_amount and amount < ROUNDING_LEFTOVER
                               and amount < adjustment.monthly_amount):
                continue

            att_type = Type._for_salary_adjustment(adjustment)
            advance = Advance.search([('salary_adjustment_id', '=', adjustment.id)], limit=1)
            claim = [
                ('employee_id', '=', employee.id), ('month', '=', month), ('year', '=', year),
                ('salary_adjustment_id', '=', False), ('state', '!=', 'paid'),
            ]
            if advance:
                claim.append(('advance_id', '=', advance.id))
            else:
                claim += [('type_id', '=', att_type.id), ('advance_id', '=', False),
                          ('fine_id', '=', False)]
            existing = Row.search(claim, limit=1)
            if existing:
                existing.salary_adjustment_id = adjustment.id
                made |= existing
                continue

            installment = advance.installment_ids.filtered(
                lambda i: not i.attachment_id and not i.paid
            ).sorted(lambda i: (i.due_date or date.max, i.id))[:1]
            type_name = adjustment.other_input_type_id.name or ''
            note = adjustment.description or ''
            if note.strip().lower() == type_name.strip().lower():
                note = ''  # "Phone Bill Allowance - Phone Bill Allowance" says it twice
            row = Row.create({
                'name': " - ".join(part for part in (
                    type_name, note, "%s-%s" % (month, year)) if part),
                'employee_id': employee.id,
                'type_id': att_type.id,
                'month': month,
                'year': year,
                # A negative adjustment landing on an addition type (a pension
                # contribution kept as an addition of a negative amount) carries its
                # sign in the value, as the rows typed by hand always did.
                'value': -amount if (adjustment.is_refund and att_type.factor > 0) else amount,
                'salary_adjustment_id': adjustment.id,
                'advance_id': advance.id or False,
                'installment_id': installment.id or False,
                'auto_generated': True,
                'state': 'new',
            })
            if installment:
                installment.attachment_id = row.id
            made |= row
        return made.with_env(self.env)

    @api.model
    def _exists_for_period(self, employee, month, year, type_id, day=False):
        """True when this employee already carries an attachment of this type
        for the period. Identity is the period and the type, not the wording of
        the description: the same fact reaching us through another route would
        otherwise be paid twice. ``day`` separates several occurrences of the
        same type inside one month (sick leaves)."""
        return bool(self.search_count([
            ('employee_id', '=', employee.id),
            ('month', '=', month), ('year', '=', str(year)),
            ('type_id', '=', type_id),
            ('day', '=', day or False),
            ('state', '!=', 'paid'),
        ]))

    @api.model
    def _clear_generated_for(self, employee, month, year):
        """Drop the engine's own unpaid output for this period.

        Called before a period is generated again. A deduction that read six
        absence days last time and two this time is the same fact recalculated,
        not two facts - and the previous wording would otherwise stay attached and
        be paid alongside the new one.

        Only rows this engine wrote, and only while they are unpaid. Anything a
        person entered by hand, and anything already paid, survives.
        """
        stale = self.search([
            ('employee_id', '=', employee.id),
            ('month', '=', month), ('year', '=', str(year)),
            ('auto_generated', '=', True),
            ('state', '!=', 'paid'),
        ])
        if stale:
            _logger.info(
                "construction_payroll: replacing %s generated attachment(s) for %s in "
                "%s-%s", len(stale), employee.display_name, month, year)
            stale.with_context(construction_payroll_engine=True).unlink()
